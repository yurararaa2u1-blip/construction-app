// ========================================
// バッチスケジューラー
//
// 【なぜこのファイルが必要か】
// delayedCheck.js は「何をするか」だけを定義している。
// このファイルは「いつ実行するか」を定義する。
// 役割を分けることで、手動テストと自動実行を独立させられる。
//
// 【cron式とは】
// Unix系システムで定期実行を指定するための書き方。
// node-cron では 5フィールド: 分 時 日 月 曜日
//   '0 0 * * *'
//    │ │ │ │ └── 曜日（* = 毎日）
//    │ │ │ └──── 月（* = 毎月）
//    │ │ └────── 日（* = 毎日）
//    │ └──────── 時（0 = 0時）
//    └────────── 分（0 = 0分）
// → 毎日 0時0分 に実行
// ========================================
const cron = require('node-cron');
const { runDelayedCheck } = require('./delayedCheck');

const startScheduler = () => {
  // 毎日 0:00 JST（日本時間）に遅延判定バッチを実行する
  cron.schedule('0 0 * * *', async () => {
    console.log('[スケジューラー] 定時バッチ起動（毎日 0:00 JST）');
    try {
      await runDelayedCheck();
    } catch (err) {
      // バッチが失敗してもサーバー全体を止めない
      // なぜか: バッチのエラーでAPIサーバーが落ちるとユーザーが影響を受けるため
      console.error('[スケジューラー] バッチ実行中にエラーが発生しました:', err.message);
    }
  }, {
    timezone: 'Asia/Tokyo', // 深夜0時 = 日本時間で判定する
  });

  console.log('[スケジューラー] 起動完了 → 毎日 0:00 JST に遅延判定バッチを自動実行します');
};

module.exports = { startScheduler };
